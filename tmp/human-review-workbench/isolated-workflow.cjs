const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({headless:true});
  const context = await browser.newContext({viewport:{width:1440,height:900}});
  const page = await context.newPage();
  const jsErrors=[];
  page.on('pageerror', error => jsErrors.push(error.message));
  page.on('console', message => { if (message.type()==='error') jsErrors.push(message.text()); });
  await page.goto('http://127.0.0.1:8081', {waitUntil:'networkidle'});
  await page.locator('#userButton').click();
  await page.waitForFunction(()=>document.querySelector('#loginDialog')?.open===true);
  await page.locator('#loginEmail').fill('workbench.test@example.invalid');
  await page.locator('#loginPassword').fill('Isolated-Workbench-Test-2026!');
  await page.locator('#loginForm button[type=submit]').click();
  await page.waitForFunction(()=>document.querySelector('#loginDialog')?.open===false);
  jsErrors.length=0;
  await page.locator('.nav-item[data-view="review"]').click();
  await page.waitForSelector('.review-queue-item');
  const before=await page.request.get('http://127.0.0.1:8081/api/admin/review-queue?status=OPEN&limit=1000');
  const rows=await before.json();
  if(rows.length!==2 || rows.some(row=>row.disposition==='SOURCE_RECHECK_REQUIRED')) throw new Error('Isolated default actionable queue is not correct.');
  await page.locator('.review-queue-item').first().click();
  await page.waitForSelector('#reviewDecisionPanel h2');
  const selected=await page.locator('.review-queue-item.is-selected').getAttribute('data-review-key');
  const [domain,id]=selected.split(':');
  const detail=await (await page.request.get(`http://127.0.0.1:8081/api/admin/review-workbench/${domain}/${id}`)).json();
  await page.locator('[data-review-action="keep"]').click();
  await page.locator('#reviewDecisionReason').selectOption({index:1});
  await page.locator('#reviewPreviewButton').click();
  await page.waitForFunction(()=>document.querySelector('#reviewDecisionPreview')?.hidden===false);
  await page.once('dialog', dialog=>dialog.accept());
  await page.locator('#reviewSubmitButton').click();
  await page.waitForFunction(()=>document.querySelectorAll('.review-queue-item').length===1);
  const nextSelected=await page.locator('.review-queue-item.is-selected').getAttribute('data-review-key');
  if(nextSelected===selected) throw new Error('Next-review navigation did not advance.');
  const decided=await (await page.request.get(`http://127.0.0.1:8081/api/admin/review-workbench/${domain}/${id}`)).json();
  if(decided.status!=='RESOLVED' || !decided.audit_history.some(item=>item.after?.decision==='FIELD_KEEP')) throw new Error('Decision status or audit event was not persisted in isolated DB.');
  const [nextDomain,nextId]=nextSelected.split(':');
  const nextDetail=await (await page.request.get(`http://127.0.0.1:8081/api/admin/review-workbench/${nextDomain}/${nextId}`)).json();
  const stale=await page.request.post(`http://127.0.0.1:8081/api/admin/review-workbench/${nextDomain}/${nextId}/preview?action=keep&version_token=${'0'.repeat(64)}`);
  if(stale.status()!==409) throw new Error(`Stale-version preview returned ${stale.status()}, expected 409.`);
  await page.locator('[data-review-action]').first().click();
  await page.locator('#reviewDecisionReason').selectOption({index:1});
  let unsavedWarning=false;
  page.once('dialog', async dialog=>{unsavedWarning=dialog.type()==='confirm'; await dialog.dismiss();});
  await page.locator('#reviewPrevious').click();
  if(!unsavedWarning) throw new Error('Unsaved-change navigation warning was not shown.');
  if(jsErrors.length) throw new Error(`JavaScript console errors: ${jsErrors.join(' | ')}`);
  console.log(JSON.stringify({isolated_reviews_initial:rows.length,decision_preview:'PASSED',submission:'PASSED',audit:'PASSED',next_review_navigation:'PASSED',stale_version_rejected:'PASSED',unsaved_navigation_warning:'PASSED',js_errors:jsErrors.length,selected_review:id,next_review:nextId}));
  await browser.close();
})().catch(error=>{console.error(error.stack||error);process.exitCode=1;});
